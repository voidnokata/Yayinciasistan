// Runs in the page's MAIN world so its own XHR wrappers can participate.
// Fixed read-only endpoint only. Learns four same-origin request headers in memory.
(() => {
  if (location.origin !== 'https://live-backstage.tiktok.com') return;
  const endpoint = location.origin + '/creators/live/union_platform_api/agency/union_invite/batch_check_anchor/';
  const names = ['faction-id', 'x-appid', 'x-language', 'x-csrf-token'];
  const observed = new WeakMap();
  const ownRequests = new WeakSet();
  let contextHeaders = null;
  const presence = headers => ({
    factionId: Boolean(headers?.['faction-id']), appId: Boolean(headers?.['x-appid']),
    language: Boolean(headers?.['x-language']), csrf: Boolean(headers?.['x-csrf-token']),
    secsdkCsrf: Boolean(headers?.['x-secsdk-csrf-token'])
  });
  let latestPresence = presence(null);
  const prototype = XMLHttpRequest.prototype;
  const originalOpen = prototype.open;
  const originalHeader = prototype.setRequestHeader;
  const originalSend = prototype.send;
  prototype.open = function(method, url, ...rest) {
    const result = Reflect.apply(originalOpen, this, [method, url, ...rest]);
    observed.delete(this);
    try {
      const parsed = new URL(url, location.href);
      if (parsed.origin === location.origin && parsed.pathname.startsWith('/creators/live/union_platform_api/')) {
        observed.set(this, {});
      }
    } catch { /* Unrelated requests are untouched. */ }
    return result;
  };
  prototype.setRequestHeader = function(name, value) {
    const result = Reflect.apply(originalHeader, this, [name, value]);
    const headers = observed.get(this);
    const key = String(name).toLowerCase();
    // Cookie/Authorization and unrelated header values are never inspected or retained.
    if (headers && names.includes(key)) headers[key] = String(value);
    if (headers && key === 'x-secsdk-csrf-token') headers[key] = true;
    return result;
  };
  prototype.send = function(...args) {
    const headers = observed.get(this);
    if (!ownRequests.has(this) && names.some(name => headers?.[name])) latestPresence = presence(headers);
    if (!ownRequests.has(this) && names.every(name => headers?.[name])) {
      // One coherent request; never combine tokens and agency IDs from different requests.
      contextHeaders = Object.fromEntries(names.map(name => [name, headers[name]]));
    }
    return Reflect.apply(originalSend, this, args);
  };
  let busy = false;
  window.addEventListener('message', event => {
    const request = event.data;
    if (event.source !== window || event.origin !== location.origin ||
        request?.channel !== 'BTG_PAGE_API_REQUEST_V1' || typeof request.id !== 'string') return;
    const reply = result => window.postMessage({ channel: 'BTG_PAGE_API_REPLY_V1', id: request.id, ...result }, location.origin);
    if (request.action === 'ping') {
      reply({ ready: true, contextReady: Boolean(contextHeaders), headerPresence: contextHeaders ? presence(contextHeaders) : latestPresence }); return;
    }
    if (request.action !== 'check') return;
    if (typeof request.username !== 'string' || !/^[a-zA-Z0-9._]{1,24}$/.test(request.username)) {
      reply({ code: 'INVALID_USERNAME' }); return;
    }
    if (busy) { reply({ code: 'BUSY' }); return; }
    if (!contextHeaders) { reply({ code: 'CONTEXT_NOT_READY', headerPresence: latestPresence }); return; }
    busy = true;
    let done = false;
    let timer;
    let xhr;
    const finish = result => {
      if (done) return;
      done = true;
      busy = false;
      clearTimeout(timer);
      reply({ ...result, headerPresence: presence(observed.get(xhr)) });
    };
    try {
      xhr = new XMLHttpRequest();
      ownRequests.add(xhr);
      xhr.open('POST', endpoint, true);
      xhr.withCredentials = true;
      xhr.timeout = 12000;
      xhr.setRequestHeader('Content-Type', 'application/json');
      xhr.setRequestHeader('Accept', 'application/json, text/plain, */*');
      for (const name of names) xhr.setRequestHeader(name, contextHeaders[name]);
      // X-Secsdk-Csrf-Token is generated by TikTok's SDK; do not replay it or add duplicates.
      xhr.onload = () => {
        try {
          const finalURL = new URL(xhr.responseURL || endpoint);
          if (finalURL.origin !== location.origin || finalURL.pathname !== new URL(endpoint).pathname) {
            finish({ code: 'REDIRECT', httpStatus: xhr.status }); return;
          }
          const body = xhr.responseText;
          if (body.length > 131072) { finish({ code: 'INVALID_RESPONSE', httpStatus: xhr.status }); return; }
          const contentType = xhr.getResponseHeader?.('content-type') || '';
          const contentKind = /json/i.test(contentType) ? 'json' : /html/i.test(contentType) ? 'html'
            : /^text\//i.test(contentType) ? 'text' : contentType ? 'other' : 'unknown';
          finish({ httpStatus: xhr.status, body, contentKind,
            // Presence only, never values. These flags are diagnostic, not proof of valid signing.
            signatureFields: {
              msToken: finalURL.searchParams.has('msToken'),
              xBogus: finalURL.searchParams.has('X-Bogus'),
              xGnarly: finalURL.searchParams.has('X-Gnarly')
            }
          });
        } catch { finish({ code: 'INVALID_RESPONSE' }); }
      };
      xhr.onerror = () => finish({ code: 'NETWORK_ERROR' });
      xhr.ontimeout = () => finish({ code: 'TIMEOUT' });
      xhr.onabort = () => finish({ code: 'ABORTED' });
      timer = setTimeout(() => { finish({ code: 'TIMEOUT' }); xhr.abort(); }, 12500);
      xhr.send(JSON.stringify({ DisplayIDList: [request.username], RecommendDisplayIDList: [] }));
    } catch { finish({ code: 'NETWORK_ERROR' }); }
  });
})();
