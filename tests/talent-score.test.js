const assert = require('node:assert/strict');
const {number,clock,parseHistory,assess} = require('../src/core/talent-score');
const {describe} = require('../src/core/talent-score');
const {activeDaysAllowed} = require('../src/core/talent-score');
assert.equal(activeDaysAllowed({metrics:{activeDays:4}},true),false);
assert.equal(activeDaysAllowed({metrics:{activeDays:5}},true),true);
assert.equal(activeDaysAllowed({metrics:{activeDays:6}},true),true);
assert.equal(activeDaysAllowed({metrics:{activeDays:null}},true),false);
assert.equal(activeDaysAllowed({metrics:{activeDays:0}},false),true);
assert.equal(activeDaysAllowed({},false),true);
assert.equal(describe({followers:100000,activeDays:2,medianLikes:500,fans:0}), 'Çok yüksek takipçi sayısı, ancak seyrek yayın.');
assert.equal(describe({followers:250,activeDays:10,medianLikes:2000,fans:0}), 'Çok düzenli yayın, ancak düşük takipçi sayısı.');
assert.equal(describe({followers:30000,activeDays:null,medianLikes:null,fans:null}), 'Yüksek takipçi sayısı; yayın geçmişi okunamadı.');
assert.equal(describe({followers:null,activeDays:null,medianLikes:null,fans:null}), 'Değerlendirme için veri sınırlı.');
const now = new Date(2026,8,7,15,13);
const fixture = `Hayran Kulübü\n12\nHediye Galerisi\n0 / 10\nGeçmiş\nEyl\n5\nGit\nCumartesi, 4:33 PM - 4:45 PM · 1.0K beğeni\nEyl\n4\nYayın\nCuma, 2:10 PM - 3:45 PM · 626 beğeni\nEyl\n4\nYayın\nCuma, 11:09 AM - 2:10 PM · 3.7K beğeni`;
assert.equal(number('1,5K'),1500);
assert.equal(number('12.360'),12360);
assert.equal(number(''),null);
assert.equal(clock('12:00 AM'),0);
assert.equal(clock('12:00 PM'),720);
assert.equal(clock('0:30 AM'),null);
assert.equal(clock('00:30 PM'),null);
assert.equal(clock('00:30'),30);
assert.equal(clock('1:30 AM'),90);
assert.equal(clock('25:10'),null);
assert.equal(parseHistory('Geçmiş\nEyl\n5\nYayın\n0:30 AM - 1:30 AM · 1K beğeni',now).known,false);
const parsed = parseHistory(fixture,now);
assert.equal(parsed.sessions.length,3);
const result = assess({text:fixture,now,followerCount:358,viewers:13});
assert.equal(result.metrics.activeDays,3);
assert.equal(result.metrics.hours,288/60);
assert.equal(result.metrics.medianLikes,1000);
assert.equal(result.metrics.fans,12);
assert.equal(result.classId,1);
assert.equal(result.coverage,100);
const missing = assess({now});
assert.equal(missing.classId,1);
assert.equal(missing.limited,true);
assert.equal(missing.metrics.activeDays,null);
assert.equal(assess({now,followerCount:0}).classId,0);
assert.equal(assess({now,followerCount:99}).classId,0);
assert.equal(assess({now,followerCount:100}).classId,1);
assert.notEqual(assess({now,followerCount:50,viewers:30}).classId,0);
assert.notEqual(assess({text:fixture,now,followerCount:50}).classId,0);
assert.equal(assess({now,followerCount:100000}).classId,3);
assert.equal(assess({now,followerCount:30000}).classId,3);
assert.notEqual(assess({now,followerCount:29999}).classId,3);
const established = assess({text:fixture,now,followerCount:30000,viewers:0});
assert.equal(established.classId,3);
assert.ok(established.score < 70);
assert.match(established.reason,/30 bin\+/);
const midnight = parseHistory('Geçmiş\nEyl\n6\nYayın\nPazar, 11:30 PM - 12:30 AM · 500 beğeni',now);
assert.equal(midnight.sessions[0].end-midnight.sessions[0].start,60);
const rollover = parseHistory('Geçmiş\nAra\n31\nYayın\nÇarşamba, 23:30 - 00:30 · 1K beğeni',new Date(2027,0,2));
assert.equal(new Date(rollover.sessions[0].day).getFullYear(),2026);
const repeated = fixture + '\n' + fixture.split('Geçmiş\n')[1];
assert.equal(parseHistory(repeated,now).sessions.length,3);
const strongText = 'Hayran Kulübü\n500\nGeçmiş\n' + Array.from({length:10},(_,i)=>`Ağu\n${31-i}\nYayın\nPazartesi, 10:00 AM - 12:00 PM · 10K beğeni`).join('\n');
assert.equal(assess({text:strongText,now:new Date(2026,8,1),followerCount:20000,viewers:100}).classId,3);
console.log('Tek tarama: gerçek panel biçimi, tarih, süre, eksik veri ve sınıflandırma testleri geçti.');
